"""The Xihoumen model made ready for time histories.

    python benchmarks/xihoumen_dynamic.py                 # cases/_xihoumen_dead.yaml, _xihoumen_rest.yaml
    python -m vfife run cases/_xihoumen_dead.yaml         # the dead state, ~1.5 min
    python -m vfife run cases/_xihoumen_rest.yaml         # 5 s at rest from it, ~3.5 min

`cases/_xihoumen.yaml` is a MODAL model: no loads, relaxation, and
massless stiff links wherever the design paper gives a connection and no
member -- the stay anchors inside the tower, the arms from the boxes to the
anchor points, the crossbeams whose steel is booked in the boxes. For modes
that is right. For an explicit time history it put the stable step at
1.07e-7 s: 2.3 hours of wall time per second of bridge, set by the ROTATION of
a stay-anchor node that nothing depends on.

Two cases, derived from the modal one and changing nothing else in it:

  _xihoumen_dead   gravity, staged relaxation to 1e-7, and
                   `mass_scaling: {target_dt: 2.0e-5}` -- the relaxation adds the
                   same masses a dynamic run will, so the state it finds is in
                   equilibrium under the weight the dynamic run carries
  _xihoumen_rest   explicit dynamics from that state (`initial_state`), gravity
                   held, undamped, 5 s: the template every scenario starts from,
                   and the check that a scenario starts at rest

MEASURED (two-core container, numba):

  step            1.07e-7 s -> 2.00e-5 s, x187
  added mass      757.5 t, 0.176% of 430 283 t, on the 48 hanger-anchor nodes of
                  the crossbeams; rotary inertia on 268 link nodes
  modes           the lowest 40 (to 0.41 Hz, torsion included) move by at most
                  0.60% (mode 3, 0.1325 -> 0.1317 Hz)
  at rest         5 s from the dead state: largest departure 0.023 mm, kinetic
                  energy 1.7e-3 J (relaxed to 1e-7; to 1e-5 it was 2.7 mm and
                  27 J -- the drift is the relaxation's own residual). The same
                  5 s started from the mesh instead: 1.68 m and 2.7e8 J
  speed           about 42 s of wall time per second of bridge
"""
from __future__ import annotations

import pathlib

import yaml

HERE = pathlib.Path(__file__).resolve().parent
CASES = HERE.parent / "cases"
G = 9.80665
TARGET_DT = 2.0e-5

HEAD = ("# {what}\n"
        "# GENERATED by benchmarks/xihoumen_dynamic.py from cases/_xihoumen.yaml -- do not\n"
        "# edit by hand; the docstring there has the measurements.\n")


def cases():
    base = yaml.safe_load((CASES / "_xihoumen.yaml").read_text(encoding="utf-8"))
    ms = {"target_dt": TARGET_DT}
    dead = dict(base, name="xihoumen_rail_road")
    dead["loads"] = [{"region": "all", "gravity": [0.0, 0.0, -G]}]
    dead["steps"] = [{"name": "dead", "load_steps": 1, "max_steps_per_load": 600000}]
    dead["solver"] = {"backend": "numba", "mode": "relaxation", "tolerance": 1.0e-7,
                      "mass_scaling": ms}
    mon = dict(base["output"]["monitors"])
    dead["output"] = {"path": "results/_xihoumen_dead.h5", "fields": ["displacement", "rotation"],
                      "monitors": mon}
    rest = dict(base, name="xihoumen_rail_road")
    rest["loads"] = [{"region": "all", "gravity": [0.0, 0.0, -G], "amplitude": "hold"}]
    rest.pop("steps", None)
    rest["solver"] = {"backend": "numba", "mode": "dynamic", "total_time": 5.0,
                      "damping": {"type": "none"}, "mass_scaling": ms,
                      "initial_state": "../results/_xihoumen_dead.h5"}
    rest["output"] = {"path": "results/_xihoumen_rest.h5", "every": 5000,
                      "fields": ["displacement"], "monitors": mon}
    return dead, rest


def main():
    dead, rest = cases()
    for name, d, what in (
            ("_xihoumen_dead.yaml", dead,
             "Xihoumen: the dead state for time histories (gravity, mass-scaled to dt 2e-5)."),
            ("_xihoumen_rest.yaml", rest,
             "Xihoumen: 5 s at rest from the dead state -- the template scenarios start from.")):
        p = CASES / name
        p.write_text(HEAD.format(what=what) + yaml.safe_dump(d, sort_keys=False, width=100),
                     encoding="utf-8")
        print("wrote", p.relative_to(HERE.parent))


if __name__ == "__main__":
    main()
