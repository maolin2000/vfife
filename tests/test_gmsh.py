def test_tet10_midside_nodes_are_on_their_edges():
    mesh, _ = gmsh.read(path("box_tet10_v41.msh"))
    scale = np.linalg.norm(mesh.nodes[mesh.elements[:, 1]]
                           - mesh.nodes[mesh.elements[:, 0]], axis=1).mean()
    assert gmsh.verify_ordering(mesh.nodes, mesh.elements) < 1e-12 * scale


def test_the_gmsh_to_vtk_permutation_is_not_the_identity():
    """If it were, this reader would be pointless — and it is not.

    Gmsh orders tet10 edges (0,1) (1,2) (0,2) (0,3) (2,3) (1,3); the VTK
    convention library.py uses ends (1,3) (2,3). Applying Gmsh's order
    unchanged puts nodes 8 and 9 on each other's edges.
    """
    mesh, _ = gmsh.read(path("box_tet10_v41.msh"))
    un_permuted = mesh.elements[:, [0, 1, 2, 3, 4, 5, 6, 7, 9, 8]]
    assert not np.array_equal(un_permuted, mesh.elements)
    with pytest.raises(ValueError, match="node ordering is wrong"):
        gmsh.verify_ordering(mesh.nodes, un_permuted)


def test_tet10_ordering_permits_a_curved_cad_edge():
    """A valid quadratic edge need not have its mid-side node on its chord."""
    nodes = np.array([
        [0., 0., 0.], [1., 0., 0.], [0., 1., 0.], [0., 0., 1.],
        [.5, 0., .10], [.5, .5, 0.], [0., .5, 0.], [0., 0., .5],
        [.5, 0., .5], [0., .5, .5],
    ])
    conn = np.arange(10, dtype=np.int32)[None, :]
    assert gmsh.verify_ordering(nodes, conn) > 0.0
    with pytest.raises(ValueError, match="node ordering is wrong"):
        gmsh.verify_ordering(nodes, conn[:, [0, 1, 2, 3, 4, 5, 6, 7, 9, 8]])


