def test_a_case_file_can_use_a_gmsh_mesh_and_its_physical_groups(tmp_path):
    """The point of the whole feature: no bounding boxes anywhere."""
    from vfife.cli import build
    from vfife.core.solver import Solver
    from vfife.io import schema

    case_path = tmp_path / "case.yaml"
    case_path.write_text(f"""
name: imported
mesh: {{type: gmsh, path: {path('box_tet10_v41.msh')}}}
materials:
  steel: {{type: linear_elastic, E: 2.0e11, nu: 0.3, rho: 7850.0}}
sections:
  body: {{type: solid, material: steel, formulation: b-bar}}
constraints:
  - {{region: left_face, dofs: [1, 1, 1]}}
loads:
  - {{region: right_face, vector: [0.0, 0.0, -1.0e4]}}
solver: {{mode: relaxation, n_steps: 20000, tolerance: 1.0e-7, backend: numpy,
         damping: {{type: kinetic}}}}
""", encoding="utf-8")
    case, _ = schema.load(str(case_path))
    mesh, mat, element = build(case, str(case_path))
    assert element == "tet10"                 # taken from the file, not the case

    p = case.as_dict()
    p["element"] = {**p["element"], "type": element}
    s = Solver(p, mesh, mat, log=lambda *_: None).run(progress_every=200,
                                                      output_every=10 ** 9)
    tip = s.u[mesh.regions["right_face"], 2].mean()
    # stubby cantilever, L/h = 3: Euler-Bernoulli + shear gives ~9.8e-6 and
    # under-predicts a 3-D solution at this aspect ratio
    assert -2.0e-5 < tip < -8.0e-6
    assert np.abs(s.u[mesh.regions["left_face"]]).max() == 0.0


def test_a_section_cannot_name_an_element_type(tmp_path):
    """The mesh decides the element type -- tet10 here, from the file. In the
    old form a case could say `element: {type: hexa8}` over a tet10 mesh and
    had to be refused at build time. A solid section has no such field: the
    schema refuses the key before any file is read."""
    from vfife.io import schema

    case_path = tmp_path / "case.yaml"
    case_path.write_text(f"""
name: wrong
mesh: {{type: gmsh, path: {path('box_tet10_v41.msh')}}}
materials:
  steel: {{type: linear_elastic, E: 2.0e11, nu: 0.3, rho: 7850.0}}
sections:
  body: {{type: solid, material: steel, element: hexa8}}
solver: {{mode: relaxation, n_steps: 10}}
""", encoding="utf-8")
    with pytest.raises(ValueError, match="element"):
        schema.load(str(case_path))

def test_an_unknown_region_lists_what_is_available():
    from vfife.core.solver import Solver

    mesh, element = gmsh.read(path("box_tet4_v41.msh"))
    mat = create("linear_elastic", E=2e11, nu=0.3, rho=7850.0)
    prob = {
        "element": {"type": element, "formulation": "full"},
        "constraints": [{"region": "bottom", "dofs": [1, 1, 1]}],
        "solver": {"mode": "relaxation", "n_steps": 10},
    }
    with pytest.raises(ValueError, match="left_face, right_face, solid"):
        Solver(prob, mesh, mat, log=lambda *_: None)
