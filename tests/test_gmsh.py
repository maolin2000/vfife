"""Gmsh import: node ordering, physical groups, formats, and the failure modes.

The fixtures in `tests/data/` are real Gmsh output, not hand-written files —
generated by Gmsh 4.15 for a 1.2 x 0.6 x 0.4 box with three physical groups, in
every format and element type the reader claims to support. Hand-written files
would test the reader against my idea of the format rather than against the
format.

The test that actually matters is the patch test. Everything else — counts,
region sizes, formats agreeing — would still pass with a wrong mid-side node
ordering. A linear displacement field reproduced as exactly constant stress
would not.
"""

import os

import numpy as np
import pytest

from vfife.elements import continuum
from vfife.io import gmsh
from vfife.materials import create

DATA = os.path.join(os.path.dirname(__file__), "data")


def path(name):
    return os.path.join(DATA, name)


ALL = ["box_tet4_v41.msh", "box_tet4_v22.msh", "box_tet4_bin.msh",
       "box_tet10_v41.msh", "box_tet10_v22.msh", "box_hexa8_v41.msh",
       "box_wedge6_v41.msh"]

EXPECTED = {"box_tet4_v41.msh": "tet4", "box_tet4_v22.msh": "tet4",
            "box_tet4_bin.msh": "tet4", "box_tet10_v41.msh": "tet10",
            "box_tet10_v22.msh": "tet10", "box_hexa8_v41.msh": "hexa8",
            "box_wedge6_v41.msh": "wedge6"}


@pytest.mark.parametrize("name", ALL)
def test_reads_and_reports_its_element_type(name):
    mesh, element = gmsh.read(path(name))
    assert element == EXPECTED[name]
    assert mesh.n_elem > 0
    # the box is 1.2 x 0.6 x 0.4 at the origin
    assert np.allclose(mesh.nodes.min(axis=0), [0.0, 0.0, 0.0], atol=1e-9)
    assert np.allclose(mesh.nodes.max(axis=0), [1.2, 0.6, 0.4], atol=1e-9)


@pytest.mark.parametrize("other", ["box_tet4_v22.msh", "box_tet4_bin.msh"])
def test_every_encoding_gives_the_same_mesh(other):
    """4.1 ASCII, 2.2 ASCII and 4.1 binary are three spellings of one mesh."""
    a, ea = gmsh.read(path("box_tet4_v41.msh"))
    b, eb = gmsh.read(path(other))
    assert ea == eb
    assert np.abs(a.nodes - b.nodes).max() < 1e-12
    assert np.array_equal(a.elements, b.elements)
    assert sorted(a.regions) == sorted(b.regions)
    for k in a.regions:
        assert np.array_equal(a.regions[k], b.regions[k])


@pytest.mark.parametrize("name", ALL)
def test_physical_groups_become_regions_on_the_right_nodes(name):
    """A named group is only useful if it selects what its name says."""
    mesh, _ = gmsh.read(path(name))
    assert set(mesh.regions) == {"solid", "left_face", "right_face"}
    assert np.abs(mesh.nodes[mesh.regions["left_face"], 0]).max() < 1e-9
    assert np.abs(mesh.nodes[mesh.regions["right_face"], 0] - 1.2).max() < 1e-9
    # and the volume group covers every node the mesh actually uses
    assert mesh.regions["solid"].size == mesh.n_nodes


@pytest.mark.parametrize("name,formulation", [
    ("box_tet4_v41.msh", "full"),
    ("box_tet10_v41.msh", "full"), ("box_tet10_v41.msh", "b-bar"),
    ("box_tet10_v22.msh", "full"),
    ("box_hexa8_v41.msh", "full"), ("box_hexa8_v41.msh", "b-bar"),
    ("box_hexa8_v41.msh", "reduced"),
    ("box_wedge6_v41.msh", "full"), ("box_wedge6_v41.msh", "b-bar"),
])
def test_patch_test_on_imported_meshes(name, formulation):
    """The test with teeth: a wrong node ordering cannot survive this.

    A linear displacement field must produce exactly constant stress. Element
    counts and region sizes would look right with the mid-side nodes permuted;
    this would not.
    """
    mesh, element = gmsh.read(path(name))
    E, nu = 3.0e10, 0.2
    mat = create("linear_elastic", E=E, nu=nu, rho=2400.0)
    A = np.array([[3.0e-4, 1.0e-4, -2.0e-4],
                  [1.0e-4, -1.0e-4, 5.0e-5],
                  [-2.0e-4, 5.0e-5, 2.0e-4]])
    A = 0.5 * (A + A.T)

    pre = continuum.precompute(mesh.nodes, mesh.elements, element=element,
                               formulation=formulation, material=mat)
    x0 = mesh.nodes[mesh.elements]
    x0_e = np.ascontiguousarray(x0 - x0.mean(axis=1, keepdims=True))
    u = mesh.nodes @ A.T
    state = mat.init_state(pre.n_elem * pre.n_gp)
    quat = np.zeros((pre.n_elem, 4))
    quat[:, 0] = 1.0
    _f, sig = continuum.internal_force(pre, x0_e, u[mesh.elements], quat, mat,
                                       state, 1.0, rot_iters=40,
                                       want_stress=True)
    lam = E * nu / ((1 + nu) * (1 - 2 * nu))
    G = E / (2 * (1 + nu))
    tr = np.trace(A)
    exact = np.array([lam * tr + 2 * G * A[0, 0], lam * tr + 2 * G * A[1, 1],
                      lam * tr + 2 * G * A[2, 2], 2 * G * A[0, 1],
                      2 * G * A[1, 2], 2 * G * A[2, 0]])
    err = np.abs(sig - exact).max() / np.abs(exact).max()
    assert err < 1e-10, f"{element}/{formulation}: {err:.3e}"


