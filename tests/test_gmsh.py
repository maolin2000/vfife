def test_scale_multiplies_the_geometry():
    """Meshing in mm and analysing in m is the normal case, not the exception."""
    a, _ = gmsh.read(path("box_tet4_v41.msh"))
    b, _ = gmsh.read(path("box_tet4_v41.msh"), scale=0.001)
    assert np.allclose(b.nodes, a.nodes * 0.001)
    assert np.array_equal(a.elements, b.elements)


def test_orphan_nodes_are_pruned():
    """A node no element uses would arrive with no stiffness and no mass."""
    mesh, _ = gmsh.read(path("box_tet4_v41.msh"))
    used = np.unique(mesh.elements)
    assert used.size == mesh.n_nodes
    assert used.min() == 0 and used.max() == mesh.n_nodes - 1


@pytest.mark.parametrize("name", ALL)
def test_every_element_is_positively_oriented(name):
    """precompute rejects a negative Jacobian; import should never hand it one."""
    mesh, element = gmsh.read(path(name))
    mat = create("linear_elastic", E=3e10, nu=0.2, rho=2400.0)
    pre = continuum.precompute(mesh.nodes, mesh.elements, element=element,
                               formulation="full", material=mat)
    assert (pre.volume > 0).all()


def test_inverted_elements_are_flipped_at_import():
    """Mirroring the mesh inverts every element; the reader must repair it."""
    mesh, element = gmsh.read(path("box_tet4_v41.msh"))
    mirrored = mesh.nodes.copy()
    mirrored[:, 0] *= -1.0                      # every tet now has negative volume
    x = mirrored[mesh.elements]
    vol = np.einsum("ei,ei->e", np.cross(x[:, 1] - x[:, 0], x[:, 2] - x[:, 0]),
                    x[:, 3] - x[:, 0])
    assert (vol < 0).all()

    fixed = gmsh._fix_orientation(mirrored, mesh.elements, element)
    x = mirrored[fixed]
    vol = np.einsum("ei,ei->e", np.cross(x[:, 1] - x[:, 0], x[:, 2] - x[:, 0]),
                    x[:, 3] - x[:, 0])
    assert (vol > 0).all()


